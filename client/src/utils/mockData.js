function addHoursToTime(time, durationStr) {
  const [h, m] = time.split(':').map(Number);
  const match = durationStr.match(/(\d+)h\s*(\d+)m/);
  if (!match) return { time: "06:00", nextDay: false };
  const dh = parseInt(match[1]), dm = parseInt(match[2]);
  let totalM = h * 60 + m + dh * 60 + dm;
  const nextDay = totalM >= 1440;
  totalM = totalM % 1440;
  return {
    time: `${String(Math.floor(totalM/60)).padStart(2,'0')}:${String(totalM%60).padStart(2,'0')}`,
    nextDay,
  };
}

