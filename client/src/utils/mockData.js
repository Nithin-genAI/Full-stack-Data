// Seat layout generator
export function generateSeatLayout(busType, totalSeats) {
  const layout = { lowerDeck: [], upperDeck: [] };
  const cols = busType === 'Seater' ? 4 : 3;
  const rows = Math.ceil(totalSeats / cols);
  let seatNum = 1;

  for (let r = 0; r < rows; r++) {
    const row = [];
    for (let c = 0; c < cols; c++) {
      if (seatNum > totalSeats) { row.push(null); continue; }
      const type = (c === 0 || c === cols - 1) ? 'window' : 'aisle';
      row.push({ id: `L${seatNum}`, row: r + 1, col: c + 1, type, status: 'available' });
      seatNum++;
    }
    // Insert aisle gap
    if (cols === 4) row.splice(2, 0, null);
    else if (cols === 3) row.splice(2, 0, null);
    layout.lowerDeck.push(row);
  }
  return layout;
}

export function generateBookedSeats(layout, bookedCount) {
  const allSeats = layout.lowerDeck.flat().filter(Boolean);
  const indices = [];
  while (indices.length < Math.min(bookedCount, allSeats.length)) {
    const idx = Math.floor(Math.random() * allSeats.length);
    if (!indices.includes(idx)) indices.push(idx);
  }
  indices.forEach(i => { allSeats[i].status = 'booked'; });
  return layout;
}

// Search API simulation
export const searchBuses = async (from, to, date, filters = {}) => {
  await new Promise(r => setTimeout(r, 800 + Math.random() * 700));
  let results = buses.filter(b => b.departure.location === from && b.arrival.location === to);

  if (filters.departureTime?.length) {
    results = results.filter(b => {
      const h = parseInt(b.departure.time.split(':')[0]);
      return filters.departureTime.some(f => {
        if (f === 'early') return h < 6;
        if (f === 'morning') return h >= 6 && h < 12;
        if (f === 'afternoon') return h >= 12 && h < 18;
        if (f === 'evening') return h >= 18;
        return false;
      });
    });
  }
  if (filters.busType?.length) {
    results = results.filter(b => filters.busType.includes(b.acType) || filters.busType.includes(b.type));
  }
  if (filters.operatorType?.length) {
    results = results.filter(b => filters.operatorType.includes(b.operatorType));
  }
  if (filters.rating) {
    results = results.filter(b => b.rating >= filters.rating);
  }
  if (filters.priceRange) {
    results = results.filter(b => b.basePrice >= filters.priceRange[0] && b.basePrice <= filters.priceRange[1]);
  }
  return results;
};

